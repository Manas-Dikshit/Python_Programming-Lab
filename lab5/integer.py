# Integer datatype: whole numbers, +ve / -ve, no size limit
a = 25
b = -7
big = 98765432101234567890

print("a =", a, " b =", b, " big =", big)
print("type(a) :", type(a))

print("a + b :", a + b)
print("a * b :", a * b)
print("a // 4:", a // 4)   # integer division
print("a % 4  :", a % 4)   # remainder
print("a ** 2 :", a ** 2)  # power

print("binary :", bin(a))
print("octal  :", oct(a))
print("hex    :", hex(a))
print("int('42') :", int("42"))
