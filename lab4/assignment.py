# Assignment operators: = += -= *= /= //= %= **=
a = 17
b = 5

x = a
print("x = a      :", x)

x += b
print("x += b     :", x)

x -= b
print("x -= b     :", x)

x *= 2
print("x *= 2     :", x)

x /= 4
print("x /= 4     :", x)

x //= 3
print("x //= 3    :", x)

x %= 5
print("x %= 5     :", x)

x **= 2
print("x **= 2    :", x)
