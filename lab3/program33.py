# Create variables of different data types and display their types using type().
num_int = 25
num_float = 3.14
text = "Hello Python"
flag = True
complex_num = 2 + 3j

print(num_int, "->", type(num_int))
print(num_float, "->", type(num_float))
print(text, "->", type(text))
print(flag, "->", type(flag))
print(complex_num, "->", type(complex_num))
